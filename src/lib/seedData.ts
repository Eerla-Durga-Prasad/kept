export async function initializeDatabaseSeed(): Promise<void> {
  const householdCount = await db.households.count();
  if (householdCount === 0) {
    await db.households.add(SEED_HOUSEHOLD);
    await db.household_members.bulkAdd(SEED_MEMBERS);
    await db.lists.add(SEED_LIST);
    await db.items.bulkAdd(SEED_ITEMS);
    await db.recipes.bulkAdd(SEED_RECIPES);
    await db.meals.bulkAdd(SEED_MEALS);
  }
}

export async function resetDatabaseToSeed(): Promise<void> {
  await db.transaction(
    'rw',
    [
      db.households,
      db.household_members,
      db.lists,
      db.items,
      db.recipes,
      db.meals,
      db.outbox_operations,
    ],
    async () => {
      await db.households.clear();
      await db.household_members.clear();
      await db.lists.clear();
      await db.items.clear();
      await db.recipes.clear();
      await db.meals.clear();
      await db.outbox_operations.clear();

      await db.households.add(SEED_HOUSEHOLD);
      await db.household_members.bulkAdd(SEED_MEMBERS);
      await db.lists.add(SEED_LIST);
      await db.items.bulkAdd(SEED_ITEMS);
      await db.recipes.bulkAdd(SEED_RECIPES);
      await db.meals.bulkAdd(SEED_MEALS);
    }
  );
}
